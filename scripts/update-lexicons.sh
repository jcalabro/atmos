#!/usr/bin/env bash
# Fetch, cache, and generate the latest upstream lexicons.
set -euo pipefail

readonly script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
readonly repo_root="$(cd -- "${script_dir}/.." && pwd)"
cd "${repo_root}"

readonly cache_dir="lexicons"
readonly work_dir="$(mktemp -d "${PWD}/.update-lexicons.XXXXXX")"
readonly staged_lexicons="${work_dir}/lexicons"
readonly lock_file="lexgen.lock"
readonly staged_lock="${work_dir}/${lock_file}"
readonly staged_api="${work_dir}/generated"
readonly previous_dir="${work_dir}/previous"
readonly discarded_dir="${work_dir}/discarded"
declare -a output_dirs=(api/bsky api/chatbsky api/comatproto api/ozone api/statusphere api/lextypes)
declare -a saved_paths=()
declare -a published_paths=()
published=0

restore_previous() {
    local target previous discarded
    local i
    local rollback_failed=0

    # First clear every newly published target, including targets that did
    # not exist before the update and therefore have no saved counterpart.
    for ((i = ${#published_paths[@]} - 1; i >= 0; i--)); do
        target="${published_paths[i]}"
        discarded="${discarded_dir}/${target}"
        if [[ -e "${target}" ]]; then
            if ! mkdir -p "$(dirname "${discarded}")" || ! mv "${target}" "${discarded}"; then
                printf 'failed to preserve replacement %s during rollback\n' "${target}" >&2
                rollback_failed=1
            fi
        fi
    done
    for ((i = ${#saved_paths[@]} - 1; i >= 0; i--)); do
        target="${saved_paths[i]}"
        previous="${previous_dir}/${target}"
        if [[ -e "${previous}" ]]; then
            if [[ -e "${target}" ]] || ! mkdir -p "$(dirname "${target}")" || ! mv "${previous}" "${target}"; then
                printf 'failed to restore %s during rollback\n' "${target}" >&2
                rollback_failed=1
            fi
        fi
    done
    return "${rollback_failed}"
}

cleanup() {
    local status=$?
    trap - EXIT HUP INT TERM
    if (( ! published )) && ! restore_previous; then
        printf 'rollback failed; preserving %s for manual recovery\n' "${work_dir}" >&2
        exit 1
    fi
    rm -rf -- "${work_dir}"
    exit "${status}"
}
trap cleanup EXIT HUP INT TERM

# Copying file-by-file makes an overlap between sources an explicit error
# instead of allowing copy order to select a source silently.
copy_tree() {
    local source="$1"
    local target="$2"
    local path relative destination

    [[ -d "${source}" ]] || {
        printf 'expected lexicon directory %s to exist\n' "${source}" >&2
        return 1
    }
    while IFS= read -r -d '' path; do
        relative="${path#"${source}"/}"
        destination="${target}/${relative}"
        if [[ -e "${destination}" ]]; then
            printf 'lexicon source collision at %s\n' "${destination}" >&2
            return 1
        fi
        mkdir -p "$(dirname "${destination}")"
        cp -p "${path}" "${destination}"
    done < <(find "${source}" -type f -print0 | sort -z)
}

clone_source() {
    local name="$1"
    local url="$2"
    local checkout="${work_dir}/${name}"

    git clone --depth 1 --no-tags "${url}" "${checkout}"
    printf '%s %s %s\n' "${name}" "${url}" "$(git -C "${checkout}" rev-parse HEAD)" >> "${staged_lock}"
}

mkdir -p "${staged_lexicons}"
printf '# Generated by just update-lexicons. Do not edit.\n# source URL commit\n' > "${staged_lock}"

clone_source atproto https://github.com/bluesky-social/atproto.git
clone_source bsky https://github.com/bluesky-social/bsky.git
clone_source statusphere-example-app https://github.com/bluesky-social/statusphere-example-app.git

# atproto also contains mirrored bsky lexicons. Excluding those two trees
# establishes bsky as their sole authority while retaining every other
# atproto namespace in the cache.
for source in "${work_dir}/atproto/lexicons"/*; do
    [[ -d "${source}" ]] || continue
    case "$(basename "${source}")" in
        app|chat) continue ;;
    esac
    copy_tree "${source}" "${staged_lexicons}/$(basename "${source}")"
done
copy_tree "${work_dir}/bsky/lexicons" "${staged_lexicons}"
copy_tree "${work_dir}/statusphere-example-app/lexicons" "${staged_lexicons}"

# Keep tests and other handwritten files, replace only generated Go files,
# and generate into a staging tree before publishing any checked-in paths.
for output_dir in "${output_dirs[@]}"; do
    mkdir -p "${staged_api}/$(dirname "${output_dir}")"
    cp -a "${output_dir}" "${staged_api}/${output_dir}"
    find "${staged_api}/${output_dir}" -type f -name '*.go' -exec grep -IlZ '^// Code generated by lexgen\. DO NOT EDIT\.$' {} + | xargs -0r rm -f
done
go run ./cmd/lexgen -lexdir "${staged_lexicons}" -config lexgen.json -output-root "${staged_api}"

# Publish the cache and every generated package as one rollbackable set.
# Same-filesystem renames ensure that a normal failure or interruption
# restores the prior cache and API together.
for target in "${cache_dir}" "${lock_file}" "${output_dirs[@]}"; do
    if [[ -e "${target}" ]]; then
        mkdir -p "${previous_dir}/$(dirname "${target}")"
        mv "${target}" "${previous_dir}/${target}"
        saved_paths+=("${target}")
    fi
done
published_paths+=("${cache_dir}")
mv "${staged_lexicons}" "${cache_dir}"
published_paths+=("${lock_file}")
mv "${staged_lock}" "${lock_file}"
for output_dir in "${output_dirs[@]}"; do
    mkdir -p "$(dirname "${output_dir}")"
    published_paths+=("${output_dir}")
    mv "${staged_api}/${output_dir}" "${output_dir}"
done
published=1

#!/usr/bin/env bash
# Refresh the checked-in spaces overlay from an explicit immutable atproto SHA.
set -euo pipefail

if [[ $# -ne 1 || ! "$1" =~ ^[0-9a-f]{40}$ ]]; then
    printf 'usage: %s <40-character-atproto-commit>\n' "$0" >&2
    exit 2
fi
readonly requested_sha="$1"
readonly source_url="https://github.com/bluesky-social/atproto.git"
readonly script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
readonly repo_root="$(cd -- "${script_dir}/.." && pwd)"
cd "${repo_root}"

readonly work_dir="$(mktemp -d "${PWD}/.update-space-lexicons.XXXXXX")"
readonly checkout="${work_dir}/atproto"
readonly staged_overlay="${work_dir}/lexicons-space"
readonly staged_lock="${work_dir}/space-lexgen.lock"
readonly staged_api="${work_dir}/generated"
readonly previous_dir="${work_dir}/previous"
readonly discarded_dir="${work_dir}/discarded"
declare -a output_dirs=(api/bsky api/chatbsky api/comatproto api/ozone api/statusphere api/lextypes)
declare -a saved_paths=()
declare -a published_paths=()
published=0

restore_previous() {
    local target previous discarded
    local i
    local rollback_failed=0
    for ((i = ${#published_paths[@]} - 1; i >= 0; i--)); do
        target="${published_paths[i]}"
        discarded="${discarded_dir}/${target}"
        if [[ -e "${target}" ]]; then
            if ! mkdir -p "$(dirname "${discarded}")" || ! mv "${target}" "${discarded}"; then
                rollback_failed=1
            fi
        fi
    done
    for ((i = ${#saved_paths[@]} - 1; i >= 0; i--)); do
        target="${saved_paths[i]}"
        previous="${previous_dir}/${target}"
        if [[ -e "${previous}" ]]; then
            if [[ -e "${target}" ]] || ! mkdir -p "$(dirname "${target}")" || ! mv "${previous}" "${target}"; then
                rollback_failed=1
            fi
        fi
    done
    return "${rollback_failed}"
}

cleanup() {
    local status=$?
    trap - EXIT HUP INT TERM
    if (( ! published )) && ! restore_previous; then
        printf 'rollback failed; preserving %s for manual recovery\n' "${work_dir}" >&2
        exit 1
    fi
    rm -rf -- "${work_dir}"
    exit "${status}"
}
trap cleanup EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

git init -q "${checkout}"
git -C "${checkout}" remote add origin "${source_url}"
git -C "${checkout}" fetch -q --depth 1 origin "${requested_sha}"
git -C "${checkout}" checkout -q --detach FETCH_HEAD
actual_sha="$(git -C "${checkout}" rev-parse HEAD)"
if [[ "${actual_sha}" != "${requested_sha}" ]]; then
    printf 'fetched commit %s, expected %s\n' "${actual_sha}" "${requested_sha}" >&2
    exit 1
fi

mkdir -p "${staged_overlay}/com/atproto"
cp -a "${checkout}/lexicons/com/atproto/space" "${staged_overlay}/com/atproto/"
cp -a "${checkout}/lexicons/com/atproto/simplespace" "${staged_overlay}/com/atproto/"
printf '# Immutable AT Protocol spaces overlay used by jc/spaces.\n# source URL commit paths\natproto %s %s lexicons/com/atproto/space lexicons/com/atproto/simplespace\n' \
    "${source_url}" "${requested_sha}" > "${staged_lock}"

[[ -d lexicons ]] || {
    printf 'main lexicon cache is absent; run just hydrate-lexicons\n' >&2
    exit 1
}
for output_dir in "${output_dirs[@]}"; do
    mkdir -p "${staged_api}/$(dirname "${output_dir}")"
    cp -a "${output_dir}" "${staged_api}/${output_dir}"
    find "${staged_api}/${output_dir}" -type f -name '*.go' -exec grep -IlZ '^// Code generated by lexgen\. DO NOT EDIT\.$' {} + | xargs -0r rm -f
done
go run ./cmd/lexgen -lexdir lexicons -lexdir "${staged_overlay}" -config lexgen.json -output-root "${staged_api}"

for target in lexicons-space space-lexgen.lock "${output_dirs[@]}"; do
    if [[ -e "${target}" ]]; then
        mkdir -p "${previous_dir}/$(dirname "${target}")"
        mv "${target}" "${previous_dir}/${target}"
        saved_paths+=("${target}")
    fi
done
published_paths+=(lexicons-space)
mv "${staged_overlay}" lexicons-space
published_paths+=(space-lexgen.lock)
mv "${staged_lock}" space-lexgen.lock
for output_dir in "${output_dirs[@]}"; do
    mkdir -p "$(dirname "${output_dir}")"
    published_paths+=("${output_dir}")
    mv "${staged_api}/${output_dir}" "${output_dir}"
done
published=1
